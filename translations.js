/* ============================================
   LANGUAGE DETECTION & SWITCHING LOGIC
   ============================================ */

(function() {
  // SVG icons used inside translations
  const ICONS = {
    dots: '<svg class="inline-icon" viewBox="0 0 24 24" fill="currentColor"><circle cx="5" cy="12" r="2"/><circle cx="12" cy="12" r="2"/><circle cx="19" cy="12" r="2"/></svg>',
    dotsVertical: '<svg class="inline-icon" viewBox="0 0 24 24" fill="currentColor"><circle cx="12" cy="5" r="2"/><circle cx="12" cy="12" r="2"/><circle cx="12" cy="19" r="2"/></svg>',
    share: '<svg class="inline-icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M4 12v8a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2v-8"/><polyline points="16 6 12 2 8 6"/><line x1="12" y1="2" x2="12" y2="15"/></svg>'
  };

  // Detect the best initial language
  function detectLanguage() {
    // 1. Check if user has previously chosen a language
    const saved = localStorage.getItem('nh_language');
    if (saved && translations[saved]) {
      return saved;
    }
    
    // 2. Auto-detect from browser
    const browserLang = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
    
    if (browserLang.startsWith('it')) return 'it';
    if (browserLang.startsWith('ru')) return 'ru';
    return 'en'; // default
  }

  // Replace {dots}, {share}, {menu} placeholders with SVG icons
  function processIcons(text) {
    return text
      .replace(/\{dots\}/g, ICONS.dots)
      .replace(/\{share\}/g, ICONS.share)
      .replace(/\{menu\}/g, ICONS.dotsVertical);
  }

  // Apply a language to the page
  function applyLanguage(lang) {
    const dict = translations[lang] || translations.en;
    
    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        // For install instructions that contain icon placeholders, use innerHTML
        if (key === 'install.ios' || key === 'install.android') {
          el.innerHTML = processIcons(dict[key]);
        } else {
          el.textContent = dict[key];
        }
      }
    });
    
    // Update the HTML lang attribute
    document.documentElement.lang = lang;
    
    // Update language switcher label
    const langLabel = document.getElementById('langLabel');
    if (langLabel) {
      langLabel.textContent = lang.toUpperCase();
    }
    
    // Update active state in the menu
    document.querySelectorAll('.lang-option').forEach(option => {
      if (option.getAttribute('data-lang') === lang) {
        option.classList.add('active');
      } else {
        option.classList.remove('active');
      }
    });
  }

  // Switch language and remember choice
  function switchLanguage(lang) {
    if (!translations[lang]) return;
    localStorage.setItem('nh_language', lang);
    applyLanguage(lang);
    
    // Close the dropdown
    document.getElementById('langDropdown')?.classList.remove('open');
  }

  // Toggle the language dropdown menu
  function toggleDropdown(e) {
    e.stopPropagation();
    const dropdown = document.getElementById('langDropdown');
    if (dropdown) {
      dropdown.classList.toggle('open');
    }
  }

  // Close dropdown when clicking outside
  function closeDropdownOnOutsideClick(e) {
    const switcher = document.getElementById('langSwitcher');
    if (switcher && !switcher.contains(e.target)) {
      document.getElementById('langDropdown')?.classList.remove('open');
    }
  }

  // Initialize when DOM is ready
  function init() {
    // Apply initial language
    const currentLang = detectLanguage();
    applyLanguage(currentLang);
    
    // Wire up the switcher button
    const switcherBtn = document.getElementById('langSwitcherBtn');
    if (switcherBtn) {
      switcherBtn.addEventListener('click', toggleDropdown);
    }
    
    // Wire up language options
    document.querySelectorAll('.lang-option').forEach(option => {
      option.addEventListener('click', (e) => {
        e.stopPropagation();
        const lang = option.getAttribute('data-lang');
        switchLanguage(lang);
      });
    });
    
    // Close dropdown when clicking outside
    document.addEventListener('click', closeDropdownOnOutsideClick);
  }

  // Run init when ready
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
